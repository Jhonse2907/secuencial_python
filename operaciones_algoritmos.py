import math
a=float(input("Ingrese el numero a operar "))
seno=math.sin(a)
coseno=math.cos(a)
tan=math.tan(a)
raiz=math.sqrt(a)
log=math.log(a)
log10=math.log10(a)
print("El seno de ",a, " es: ",seno)
print("El coseno de ",a, " es: ",coseno)
print("La tangente de ",a, " es: ",tan)
print("La raiz de ",a, " es: ",raiz)
print("El logaritmo natural de ",a, " es: ",log)
print("El logaritmo base 10 de ",a, " es: ",log10)